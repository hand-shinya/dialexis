TABLE = {new: old for new, old in _RAW.items() if new != old}
REVERSE = {old: new for new, old in TABLE.items()}
MAX_VARIANTS = 8


def _subs(ch: str) -> tuple:
    """この1字が取りうる表記（自分自身を先頭に置く）。"""
    other = TABLE.get(ch) or REVERSE.get(ch)
    return (ch, other) if other else (ch,)


def expand(word: str, limit: int = MAX_VARIANTS) -> list:
    """語を新字体・旧字体の両方へ展開する。先頭は常に元の語。

    対応を持つ字が多い語では組み合わせが増えるため limit で打ち切る。
    打ち切りは候補の欠落であり、呼び出し側は「全て試した」と言ってはならない。
    """
    if not word:
        return [word]
    cols = [_subs(c) for c in word]
    out, seen = [], set()
    for combo in itertools.product(*cols):
        w = "".join(combo)
        if w in seen:
            continue
        seen.add(w)
        out.append(w)
        if len(out) >= limit:
            break
    return out
